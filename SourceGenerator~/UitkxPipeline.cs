        // Builtin/ambient hook names (from the single-source HookRegistry) that need no import.
        // AmbientHookNames covers BOTH spellings a file can use — canonical PascalCase
        // (UseState) and the camelCase alias (useState). CanonicalNames alone missed the
        // camelCase call sites every real file uses → UITKX2307 storm in real projects.
        private static readonly HashSet<string> s_builtinHooks =
            new HashSet<string>(global::Ruitk.Core.HookRegistry.AmbientHookNames, StringComparer.Ordinal);

        /// <summary>
        /// Validates each <c>import</c> declaration (resolves the specifier + checks the imported
        /// names are exported by the target) and appends 2300/2301/2308/2314 to
        /// <paramref name="parseDiags"/>. Uses the real filesystem + asmdef walk; export
        /// membership comes from the peer tables.
        /// </summary>
        private static void AppendImportValidationDiags(
            DirectiveSet directives,
            string filePath,
            ImmutableArray<PeerComponentInfo>? peerComponents,
            ImmutableArray<PeerHookContainerInfo>? peerHookContainers,
            List<ParseDiagnostic> parseDiags,
            ImmutableArray<PeerExportsInfo>? peerExports = null)
        {
            if (directives.Imports.IsDefaultOrEmpty)
                return;

            string importerDir = NormalizeAbs(Path.GetDirectoryName(filePath));
            string? projectRoot = AssetPathUtil.GetProjectRoot(filePath);
            string rootDir = projectRoot != null
                ? NormalizeAbs(projectRoot + "/" + UitkxConfig.LoadRoot(importerDir))
                : importerDir;
            string? importerAsmdef = FindOwningAsmdefAssemblyName(filePath);

            bool IsExportedByFile(string name, string targetPath)
            {
                string t = NormalizeAbs(targetPath);
                if (peerComponents != null)
                    foreach (var pc in peerComponents.Value)
                        if (pc.IsExported && pc.Name == name
                            && string.Equals(NormalizeAbs(pc.SourceFilePath), t, StringComparison.OrdinalIgnoreCase))
                            return true;
                if (peerHookContainers != null)
                    foreach (var ph in peerHookContainers.Value)
                        if (string.Equals(NormalizeAbs(ph.SourceFilePath), t, StringComparison.OrdinalIgnoreCase)
                            && ph.ExportedHookNames.Contains(name))
                            return true;
                // New-mode targets (ES-modules campaign): values/utils/hooks + exported components
                // live on the PeerExportsInfo surface — without this every member import out of a
                // migrated file was a false UITKX2301.
                if (peerExports != null)
                    foreach (var pe in peerExports.Value)
                    {
                        if (!string.Equals(NormalizeAbs(pe.SourceFilePath), t, StringComparison.OrdinalIgnoreCase))
                            continue;
                        if (pe.ExportedComponentNames.Contains(name))
                            return true;
                        if (!pe.Members.IsDefaultOrEmpty)
                            foreach (var m in pe.Members)
                                if (m.IsExported && m.Name == name)
                                    return true;
                    }
                return false;
            }

            var findings = StrictImportDetector.ValidateImports(
                directives, importerDir, rootDir, importerAsmdef,
                path => File.Exists(path),
                path => FindOwningAsmdefAssemblyName(path),
                IsExportedByFile,
                path =>
                {
                    if (!File.Exists(path)) return null;
                    try { return DirectiveParser.Parse(File.ReadAllText(path), path, new List<ParseDiagnostic>()); }
                    catch { return null; }
                });

            foreach (var f in findings)
                parseDiags.Add(new ParseDiagnostic
                {
                    Code = f.Code,
                    Severity = ParseSeverity.Error,
                    SourceLine = f.Line,
                    SourceColumn = Math.Max(0, f.Column),
                    EndLine = f.EndColumn > 0 ? f.Line : 0,
                    EndColumn = Math.Max(0, f.EndColumn),
                    Message = f.Message,
                });
        }

        /// <summary>
        /// UITKX2316 (namespace-import unification plan): validates each plain-namespace
        /// <c>@using</c> / <c>import "@Ns"</c> against the real compilation symbol table, appending a
        /// diagnostic anchored at the namespace token when it resolves nowhere.
        /// <para>Emitted as a <b>WARNING</b>, not an error: build-time namespace validation is only as
        /// sound as the compilation is complete (guaranteed in a real Unity build, but not provable by
        /// the analyzer), so — per the codebase's "never break an otherwise-valid build" rule — it must
        /// never be the build gate. The genuine gate remains the CS0246 the emitted <c>using</c>
        /// produces when the namespace is truly absent; 2316 just names the offending .uitkx token. The
        /// rich, error-tier, located feedback is the editor (LSP) pass. Mirrors UITKX2304's build/editor
        /// split.</para>
        /// <para>False positives are avoided by construction: the known set is the compilation's global
        /// namespace UNIONed with every peer <c>.uitkx</c> namespace (and their ancestors), so a using
        /// pointing at a namespace that only exists in OTHER generated output is never flagged.
        /// <c>static</c>/alias payloads (type targets) are out of scope for v1 — they resolve via the
        /// emitted C# / editor Roslyn pass, not this namespace-only check.</para>
        /// </summary>
        private static void AppendUsingValidationDiags(
            DirectiveSet directives,
            Compilation compilation,
            ImmutableArray<PeerComponentInfo>? peerComponents,
            ImmutableArray<PeerHookContainerInfo>? peerHookContainers,
            List<ParseDiagnostic> parseDiags,
            ImmutableArray<PeerExportsInfo>? peerExports = null)
        {
            if (directives.UsingDirectives.IsDefaultOrEmpty)
                return;

            // Generated namespaces (peer .uitkx + this file) are invisible to the pre-generation
            // compilation — seed them, with all ancestor prefixes, so they never false-positive.
            var known = new HashSet<string>(StringComparer.Ordinal);
            void AddWithAncestors(string? ns)
            {
                if (string.IsNullOrEmpty(ns)) return;
                string[] segs = ns!.Split('.');
                for (int n = 1; n <= segs.Length; n++)
                    known.Add(string.Join(".", segs, 0, n));
            }
            AddWithAncestors(directives.Namespace);
            if (peerComponents != null)
                foreach (var pc in peerComponents.Value) AddWithAncestors(pc.Namespace);
            if (peerHookContainers != null)
                foreach (var ph in peerHookContainers.Value) AddWithAncestors(ph.Namespace);
            // New-mode member-only files live ONLY on the peerExports table — without this
            // seeding, `import "@<their file-keyed ns>"` warns falsely (audit note).
            if (peerExports != null)
                foreach (var pe in peerExports.Value) AddWithAncestors(pe.Namespace);

            foreach (var u in directives.UsingDirectives)
            {
                var (kind, target, targetOffset) = UsingPayloadFacts.Classify(u.Payload);
                if (kind != UsingPayloadFacts.PayloadKind.Namespace)
                    continue; // static/alias (type targets) — out of scope for the SG namespace check
                if (target.Length == 0)
                    continue;
                if (known.Contains(target) || NamespaceExistsInCompilation(compilation, target))
                    continue;

                int col = u.PayloadColumn >= 0 ? u.PayloadColumn + targetOffset : -1;
                parseDiags.Add(new ParseDiagnostic
                {
                    Code = "UITKX2316",
                    Severity = ParseSeverity.Warning,
                    SourceLine = u.Line,
                    SourceColumn = Math.Max(0, col),
                    EndLine = col >= 0 ? u.Line : 0,
                    EndColumn = col >= 0 ? col + target.Length : 0,
                    Message =
                        $"unknown namespace `{target}` — no such namespace in this assembly or its references"
                        + (u.FromImportSyntax ? "" : " (check the spelling, or remove the @using)"),
                });
            }
        }

        /// <summary>Walks <paramref name="c"/>'s merged global namespace segment-by-segment; true when the whole dotted name resolves to a namespace.</summary>
        private static bool NamespaceExistsInCompilation(Compilation c, string dotted)
        {
            INamespaceSymbol ns = c.GlobalNamespace;
            foreach (string seg in dotted.Split('.'))
            {
                INamespaceSymbol? next = null;
                foreach (var m in ns.GetNamespaceMembers())
                    if (m.Name == seg) { next = m; break; }
                if (next == null)
                    return false;
                ns = next;
            }
            return true;
        }

        /// <summary>
        /// Runs <see cref="StrictImportDetector"/> over <paramref name="source"/> and appends its
        /// 2305/2307 findings to <paramref name="parseDiags"/>. The peer export table is built from
        /// the pre-scan peer arrays (exported names only — the frozen "exported-names ledger").
        /// </summary>
        private static void AppendStrictReferenceDiags(
            DirectiveSet directives,
            string source,
            string filePath,
            ImmutableArray<PeerComponentInfo>? peerComponents,
            ImmutableArray<PeerHookContainerInfo>? peerHookContainers,
            List<ParseDiagnostic> parseDiags)
        {
            var peerExports = new List<StrictImportDetector.PeerExport>();

            if (peerComponents != null)
                foreach (var pc in peerComponents.Value)
                    if (pc.IsExported && !string.IsNullOrEmpty(pc.SourceFilePath))
                        peerExports.Add(new StrictImportDetector.PeerExport(
                            pc.Name, pc.SourceFilePath!, StrictImportDetector.ExportKind.Component));

            if (peerHookContainers != null)
                foreach (var ph in peerHookContainers.Value)
                    if (!string.IsNullOrEmpty(ph.SourceFilePath))
                        foreach (var hookName in ph.ExportedHookNames)
                            peerExports.Add(new StrictImportDetector.PeerExport(
                                hookName, ph.SourceFilePath!, StrictImportDetector.ExportKind.Hook));

            if (peerExports.Count == 0)
                return;

            string scannable = StrictImportDetector.ScrubNonCode(source);
            var findings = StrictImportDetector.Detect(
                directives, filePath, scannable, peerExports, s_builtinHooks.Contains);
            findings.AddRange(StrictImportDetector.DetectUnusedImports(directives, scannable));

            foreach (var f in findings)
                parseDiags.Add(new ParseDiagnostic
                {
                    Code = f.Code,
                    // Heuristic findings (bare hook calls / module member access scanned out of
                    // C# expression text) are warnings — ambient C# legitimately produces those
                    // shapes, and a real missing import still fails the emitted C# (CS0103).
                    // 2304 is ERROR-tier since 0.9.1 (owner decision, consistent with the other
                    // import diagnostics): the reference universe over-approximates "used", so
                    // a 2304 only fires when the binding truly appears nowhere — no
                    // false-positive risk at error tier.
                    Severity = f.IsHeuristic ? ParseSeverity.Warning : ParseSeverity.Error,
                    SourceLine = f.Line,
                    SourceColumn = Math.Max(0, f.Column),
                    EndLine = f.EndColumn > 0 ? f.Line : 0,
                    EndColumn = Math.Max(0, f.EndColumn),
                    Message = f.Message,
                });
        }

        /// <summary>
        /// Returns <c>true</c> when the given path contains an <c>Editor</c>
        /// directory segment. Unity uses this convention to assign files without
        /// an .asmdef to <c>Assembly-CSharp-Editor</c>.
        /// </summary>
        private static bool IsInsideEditorFolder(string filePath)
        {
            foreach (
                string part in (filePath ?? string.Empty).Split(
                    new[] { Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar }
                )
            )
            {
                if (string.Equals(part, "Editor", StringComparison.OrdinalIgnoreCase))
                    return true;
            }
            return false;
        }

        /// <summary>
        /// Parses JSX ranges embedded in function-style setup code (local
        /// functions, variable assignments with JSX) into AST nodes so that
        /// hook and structural validators can inspect them.
        /// </summary>
        private static ImmutableArray<AstNode> ParseSetupCodeJsx(
            string source,
            string filePath,
            DirectiveSet directives,
            List<ParseDiagnostic> parseDiags)
        {
            var allRanges = directives.SetupCodeMarkupRanges;
            if (!directives.SetupCodeBareJsxRanges.IsDefaultOrEmpty)
            {
                allRanges = allRanges.IsDefaultOrEmpty
                    ? directives.SetupCodeBareJsxRanges
                    : allRanges.AddRange(directives.SetupCodeBareJsxRanges);
            }
            if (allRanges.IsDefaultOrEmpty)
                return ImmutableArray<AstNode>.Empty;

            var builder = ImmutableArray.CreateBuilder<AstNode>();
            foreach (var (jsxStart, jsxEnd, jsxLine) in allRanges)
            {
                var jsxDirectives = directives with
                {
                    MarkupStartIndex = jsxStart,
                    MarkupEndIndex = jsxEnd,
                    MarkupStartLine = jsxLine,
                };
                // Use a separate diag list so parse warnings from setup JSX
                // don't duplicate or interfere with the main parse diags that
                // have already been bridged to Roslyn Diagnostic objects.
                var jsxDiags = new List<ParseDiagnostic>();
                var jsxNodes = UitkxParser.Parse(source, filePath, jsxDirectives, jsxDiags);
                builder.AddRange(jsxNodes);
            }
            return builder.ToImmutable();
        }

        private static Diagnostic ParseDiagToRoslyn(ParseDiagnostic pd)
        {
            var severity =
                pd.Severity == ParseSeverity.Error ? DiagnosticSeverity.Error
                : pd.Severity == ParseSeverity.Warning ? DiagnosticSeverity.Warning
                : DiagnosticSeverity.Info;
            var desc = new DiagnosticDescriptor(
                pd.Code,
                title: "",
                messageFormat: pd.Message,
                category: "Ruitk.Parser",
                severity,
                isEnabledByDefault: true
            );
            return Diagnostic.Create(desc, Location.None);
        }

        /// <summary>
        /// Prepends <c>#error</c>/<c>#warning</c> directives to a generated source for every
        /// EMIT-STAGE diagnostic (from <paramref name="fromIndex"/> onward) that was created with
        /// <see cref="Location.None"/>. Unity silently drops Location.None diagnostics on a .uitkx
        /// (it is not a C# SyntaxTree) — the same reason the directive/parse-error path emits
        /// <c>#error</c>. Real-location diagnostics (the validators' <c>Location.Create</c>) surface
        /// on their own and are left untouched. Covers UITKX0113 (duplicate component, warning),
        /// UITKX2311 (export mismatch, warning), and later-component parse errors (error, halts).
        /// </summary>
        private static string? SurfaceLocationlessDiagnostics(
            string? source, IReadOnlyList<Diagnostic> diagnostics, int fromIndex)
        {
            if (source == null)
                return null;
            System.Text.StringBuilder? sb = null;
            for (int i = fromIndex; i < diagnostics.Count; i++)
            {
                var d = diagnostics[i];
                if (d.Location != Location.None)
                    continue; // real location → Unity surfaces it directly
                string? directive = d.Severity == DiagnosticSeverity.Error ? "#error"
                    : d.Severity == DiagnosticSeverity.Warning ? "#warning"
                    : null;
                if (directive == null)
                    continue;
                (sb ??= new System.Text.StringBuilder())
                    .Append(directive).Append(' ')
                    .Append(d.Id).Append(": ")
                    .AppendLine(d.GetMessage().Replace('\n', ' ').Replace('\r', ' '));
            }
            return sb == null ? source : sb.ToString() + source;
        }

        private static string BuildHintName(string filePath)
        {
            string fileName = Path.GetFileName(filePath);
            string normalizedPath = (filePath ?? string.Empty)
                .Replace('\\', '/')
                .ToLowerInvariant();

            using var md5 = MD5.Create();
            byte[] hash = md5.ComputeHash(Encoding.UTF8.GetBytes(normalizedPath));
            string suffix = BitConverter
                .ToString(hash, 0, 6)
                .Replace("-", string.Empty)
                .ToLowerInvariant();

            return $"{fileName}.{suffix}.g.cs";
        }
