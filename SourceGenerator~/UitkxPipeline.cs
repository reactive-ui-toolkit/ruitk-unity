    /// <summary>
    /// Top-level orchestrator for the UITKX compilation pipeline.
    ///
    /// Chain:
    ///   Stage 1 — DirectiveParser  — @namespace / @component / @using / @props / @key
    ///   Stage 2 — UitkxParser      — recursive-descent markup → AST
    ///   Stage 3 — PropsResolver    — maps tag names to V.* call patterns
    ///   Stage 4 — CSharpEmitter    — walks AST, produces compilable partial class
    ///
    /// Diagnostics produced:
    ///   UITKX0001   — unknown lowercase built-in element (warning)
    ///   UITKX0008   — unknown PascalCase function component (warning)
    ///   UITKX0113   — duplicate component name in one file (warning; duplicate skipped)
    ///   UITKX23xx   — strict import/export diagnostics (see DiagnosticCodes)
    ///   UITKX03xx   — parse errors
    /// </summary>
    public static class UitkxPipeline
    {
        public static UitkxPipelineResult Run(
            string source,
            string filePath,
            Compilation compilation,
            CancellationToken ct,
            ImmutableArray<PeerComponentInfo>? peerComponents = null,
            ImmutableArray<PeerHookContainerInfo>? peerHookContainers = null,
            IReadOnlyDictionary<string, string>? valueCycles = null,
            ImmutableArray<PeerExportsInfo>? peerExports = null
        )
        {
            ct.ThrowIfCancellationRequested();

            string fileName = Path.GetFileName(filePath);
            string hintName = BuildHintName(filePath);

            var parseDiags = new List<ParseDiagnostic>();

            // ── Stage 1: Directive parsing ────────────────────────────────────
            DirectiveSet directives = DirectiveParser.Parse(source, filePath, parseDiags);

            // ── 0.16.0 legacy removal: a wrapper-keyword file is a hard error ──
            // The parse above already attached the UITKX2320 removal error(s); emit ONLY
            // the #error stub — no legacy units, no peer participation. (The migration
            // codemod reads legacy files via DirectiveParser.ParseLegacyForMigration.)
            if (directives.UsesLegacySyntax)
            {
                var legacyDiags = new List<Diagnostic>(parseDiags.Count);
                foreach (var pd in parseDiags)
                    legacyDiags.Add(ParseDiagToRoslyn(pd));
                var legacySb = new StringBuilder();
                legacySb.AppendLine("// <auto-generated/>");
                legacySb.AppendLine($"// UITKX legacy syntax removed (0.16.0) — {fileName}");
                string legacyPath = filePath.Replace('\\', '/').Replace("\"", "\\\"");
                foreach (var pd in parseDiags)
                    if (pd.Severity == ParseSeverity.Error)
                    {
                        int errLine = pd.SourceLine > 0 ? pd.SourceLine : 1;
                        legacySb.AppendLine($"#line {errLine} \"{legacyPath}\"");
                        legacySb.AppendLine($"#error {pd.Message.Replace('\n', ' ').Replace('\r', ' ')}");
                    }
                return new UitkxPipelineResult(hintName, legacySb.ToString(), legacyDiags.ToImmutableArray());
            }

            // ── Stage 1b: Effective-namespace seam (import/export grammar, §4) ─
            // Single point where namespace identity is resolved for every downstream
            // emitter/peer read. No-op with the feature flag off (returns the parsed
            // value); path-derived when strict imports are on.
            directives = directives with { Namespace = ResolveEffectiveNamespace(directives, filePath) };

            // §7 — the file's bare-hook-name → path-qualified-family-key map. Built once from the
            // now-resolved namespace + this file's own hooks + its imports; threaded into every
            // emitter (producer + consumer) so RegisterHook ids and customHookFamilyKeys agree.
            var hookFamilyKeyMap = BuildHookFamilyKeyMap(directives, peerHookContainers, filePath);

            ct.ThrowIfCancellationRequested();

            // ── Stage 1b2: cross-backend import guard (UITKX2113) ─────────────
            // A file renders through exactly one backend; importing across the
            // @backend boundary produces code that cannot mount — this is a
            // correctness error.
            AppendCrossBackendImportDiags(directives, filePath, peerExports, parseDiags);

            // ── Stage 1c: strict import diagnostics (§6) ──
            // Import validation (2300/2301/2308/2314) + reference detector (2305/2307) + unused import
            // (2304) + value-import cycle (2306). Runs for ALL files (component AND hook/module) BEFORE
            // the short-circuit below, because hook/module files are the usual value-cycle members and
            // can reference peer hooks/modules in their bodies. Appended to the parse-diag bag so errors
            // flow through the same #error path Unity relies on.
            {
                AppendImportValidationDiags(
                    directives, filePath,
                    peerComponents, peerHookContainers, parseDiags, peerExports);
                AppendUsingValidationDiags(
                    directives, compilation,
                    peerComponents, peerHookContainers, parseDiags, peerExports);
                AppendStrictReferenceDiags(
                    directives, source, filePath,
                    peerComponents, peerHookContainers, parseDiags);
                if (valueCycles != null &&
                    valueCycles.TryGetValue(filePath.Replace('\\', '/').TrimEnd('/'), out string? cycleMsg))
                {
                    parseDiags.Add(new ParseDiagnostic
                    {
                        Code = "UITKX2306",
                        Severity = ParseSeverity.Error,
                        SourceLine = directives.Imports.IsDefaultOrEmpty ? 1 : directives.Imports[0].Line,
                        Message = cycleMsg,
                    });
                }

                // UITKX2310 (no derivable namespace) is RETIRED by design: §4 now anchors
                // path-derivation at the nearest .asmdef, else the config root (see
                // ResolveDerivationAnchor), and ResolveEffectiveNamespace additionally falls
                // back to the legacy namespace — so every file Unity actually compiles (under
                // a project root) always resolves a namespace. The code slot stays reserved in
                // the frozen family table (2310) but is never emitted; a hard #error on the
                // mainstream no-asmdef Assembly-CSharp setup would have been a false positive.
            }

            // ── Short-circuit: member-only files (no components, no markup) ──
            // ES-modules campaign (U-02): a plain-declaration file with only values/utils/hooks
            // emits its per-file __Exports container and nothing else (same guards and #error
            // surfacing as the component path).
            if (directives.ComponentName == null
                && directives.ComponentDeclarations.IsDefaultOrEmpty
                && !directives.MemberDeclarations.IsDefaultOrEmpty)
            {
                if (compilation.GetTypeByMetadataName("Ruitk.Core.VirtualNode") == null)
                    return new UitkxPipelineResult(hintName, null, ImmutableArray<Diagnostic>.Empty);
                if (!IsOwnedByCompilation(filePath, compilation.AssemblyName))
                    return new UitkxPipelineResult(hintName, null, ImmutableArray<Diagnostic>.Empty);

                var exportsDiags = new List<Diagnostic>(parseDiags.Count);
                foreach (var pd in parseDiags)
                    exportsDiags.Add(ParseDiagToRoslyn(pd));

                int exErrorCount = 0;
                foreach (var d in exportsDiags)
                    if (d.Severity == DiagnosticSeverity.Error) exErrorCount++;
                if (exErrorCount > 0)
                {
                    var errSb = new StringBuilder();
                    errSb.AppendLine("// <auto-generated/>");
                    errSb.AppendLine($"// UITKX parse errors in {fileName}");
                    string exLinePath = filePath.Replace('\\', '/').Replace("\"", "\\\"");
                    foreach (var pd in parseDiags)
                        if (pd.Severity == ParseSeverity.Error)
                        {
                            int errLine = pd.SourceLine > 0 ? pd.SourceLine : 1;
                            errSb.AppendLine($"#line {errLine} \"{exLinePath}\"");
                            errSb.AppendLine($"#error {pd.Message.Replace('\n', ' ').Replace('\r', ' ')}");
                        }
                    return new UitkxPipelineResult(hintName, errSb.ToString(), exportsDiags.ToImmutableArray());
                }

                directives = directives with
                {
                    Usings = ResolveInjectedUsings(
                        directives, peerHookContainers, filePath,
                        peerComponents, peerExports)
                };

                int exDiagStart = exportsDiags.Count;
                string exportsSource = ExportsEmitter.Emit(
                    filePath, directives, exportsDiags, hookFamilyKeyMap, peerExports);
                string? exPrimary = string.IsNullOrEmpty(exportsSource) ? null : exportsSource;
                exPrimary = SurfaceLocationlessDiagnostics(exPrimary, exportsDiags, exDiagStart);
                return new UitkxPipelineResult(hintName, exPrimary, exportsDiags.ToImmutableArray());
            }

            // (The legacy hook/module short-circuit lived here until the 0.16.0 removal —
            // wrapper-keyword files now exit at the Stage-1 legacy gate above.)

            // ── Stage 2: Markup parsing ───────────────────────────────────────
            ImmutableArray<AstNode> parsedNodes = UitkxParser.Parse(
                source,
                filePath,
                directives,
                parseDiags
            );

            // ── Stage 2b: Canonical lowering ─────────────────────────────────
            ImmutableArray<AstNode> rootNodes = CanonicalLowering.LowerToRenderRoots(
                directives,
                parsedNodes,
                filePath
            );

            // ── Stage 2c: Parse setup-code JSX ───────────────────────────────
            // Local functions (e.g. PillBar, StatusBadge) and JSX variable
            // assignments contain embedded markup that isn't part of the main
            // render root AST.  Parse those ranges into nodes so validators
            // (hooks, missing key) can check them too.
            var setupJsxNodes = ParseSetupCodeJsx(source, filePath, directives, parseDiags);

            // Bridge: convert Roslyn-free ParseDiagnostic → Roslyn Diagnostic
            // so the rest of the pipeline (validators, emitter) keep their
            // existing List<Diagnostic> API and nothing else needs to change.
            var diagnostics = new List<Diagnostic>(parseDiags.Count);
            foreach (var pd in parseDiags)
                diagnostics.Add(ParseDiagToRoslyn(pd));

            ct.ThrowIfCancellationRequested();

            // Guard 1: only emit into compilations that reference Ruitk.Shared.
            // The generator runs on every assembly in the project; assemblies that
            // don't reference Shared would get CS0246 errors for `using Ruitk;`.
            if (compilation.GetTypeByMetadataName("Ruitk.Core.VirtualNode") == null)
            {
                return new UitkxPipelineResult(
                    HintName: hintName,
                    Source: null,
                    Diagnostics: ImmutableArray<Diagnostic>.Empty
                );
            }

            // Guard 2: only emit into the compilation that *owns* this .uitkx file.
            // Multiple assemblies may reference Shared (e.g. Ruitk.Editor and
            // Ruitk.Samples both pass Guard 1). Emitting the same partial class
            // into both causes CS0101 / CS0436 duplicate-type errors.
            //
            // Ownership is determined by walking up the directory tree from the .uitkx
            // file looking for the nearest *.asmdef file. Unity always uses the nearest
            // ancestor .asmdef to decide which compiled assembly owns a given source file
            // — this generator uses the same rule so no companion .cs is required.
            //
            //   - Found .asmdef  → read its "name" field; owned when that equals
            //                      compilation.AssemblyName.
            //   - No .asmdef    → file lives in the default Assembly-CSharp (or
            //     found before       Assembly-CSharp-Editor) assembly. Unity decides
            //     reaching Assets/   between the two based on whether the file is
            //                      under an Editor/ folder. We use the same heuristic:
            //                      files under Editor/ → Assembly-CSharp-Editor,
            //                      all others → Assembly-CSharp.
            if (!IsOwnedByCompilation(filePath, compilation.AssemblyName))
            {
                return new UitkxPipelineResult(
                    HintName: hintName,
                    Source: null,
                    Diagnostics: ImmutableArray<Diagnostic>.Empty
                );
            }

            // If there are hard directive/parse errors, emit a .g.cs that contains
            // #error directives. This guarantees Unity's C# compiler surfaces the
            // errors in the Console — diagnostics with Location.None on a
            // non-SyntaxTree file are silently dropped by Unity otherwise.
            int errorCount = 0;
            foreach (var d in diagnostics)
                if (d.Severity == DiagnosticSeverity.Error)
                    errorCount++;

            if (errorCount > 0)
            {
                var sb = new System.Text.StringBuilder();
                sb.AppendLine("// <auto-generated/>");
                sb.AppendLine(
                    $"// UITKX parse errors in {fileName} — fix the .uitkx file to regenerate."
                );
                // Use #line before each #error so Unity's C# compiler reports
                // the error as originating from the .uitkx file, enabling
                // click-to-navigate in the Unity Console.
                string linePath = filePath.Replace('\\', '/').Replace("\"", "\\\"");
                foreach (var pd in parseDiags)
                    if (pd.Severity == ParseSeverity.Error)
                    {
                        int line = pd.SourceLine > 0 ? pd.SourceLine : 1;
                        sb.AppendLine($"#line {line} \"{linePath}\"");
                        sb.AppendLine($"#error {pd.Message.Replace('\n', ' ').Replace('\r', ' ')}");
                    }

                return new UitkxPipelineResult(
                    HintName: hintName,
                    Source: sb.ToString(),
                    Diagnostics: diagnostics.ToImmutableArray()
                );
            }

            ct.ThrowIfCancellationRequested();

            // Diagnostics added from here on are EMIT-STAGE; the Location.None ones among
            // them (UITKX0113, UITKX2311, later-component parse errors) would be silently
            // dropped by Unity, so they are re-surfaced as #error/#warning before returning.
            int emitDiagStart = diagnostics.Count;

            // ── Stage 3: PropsResolver ────────────────────────────────────────
            var (starNsMap, aliasTypeMap) = BuildImportAliasTagMaps(directives, filePath, peerExports);
            var resolver = new PropsResolver(
                compilation,
                peerComponents,
                starNsMap,
                aliasTypeMap,
                directives.Backend
            );

            ct.ThrowIfCancellationRequested();

            // ── Stage 3b: Rules-of-Hooks validation ───────────────────────────
            HooksValidator.Validate(rootNodes, filePath, diagnostics);
            if (!setupJsxNodes.IsEmpty)
                HooksValidator.Validate(setupJsxNodes, filePath, diagnostics);

            // ── Stage 3c: Structural validation ───────────────────────────────
            StructureValidator.Validate(rootNodes, filePath, diagnostics, directives);
            if (!setupJsxNodes.IsEmpty)
                StructureValidator.ValidateNodes(setupJsxNodes, filePath, diagnostics);

            ct.ThrowIfCancellationRequested();

            // ── Stage 3d: Inject using-static for peer hook containers ────────
            // Hook files emit into a static class (e.g. TicTacToeHooks). Components
            // need `using static <HookNs>.<HookContainer>;` so hook methods like
            // useXxx() are directly callable without qualification, regardless of
            // whether the hook file lives in the same namespace as the consumer.
            // Asmdef ownership is already enforced one layer up in UitkxGenerator's
            // pre-scan via IsOwnedByCompilation, so every entry in peerHookContainers
            // belongs to the current Unity assembly.
            // Injection exposes only imported containers (§6.2). See ResolveInjectedUsings.
            directives = directives with
            {
                Usings = ResolveInjectedUsings(
                    directives, peerHookContainers, filePath,
                    peerComponents, peerExports)
            };

            // A component body must see its own file's members (values/utils/hooks) AND any
            // imported-member bridges bare-name — both live on this file's __Exports
            // container. Injected whenever the file emits an __Exports unit (members or
            // bridges). Gate on what the __Exports unit will ACTUALLY contain — members or
            // REAL bridges — not on the import's shape. A same-name default import produces
            // NO bridge (it lowers to the container using), so a shape-based gate injected
            // `using static {ns}.__Exports` against a unit that was never emitted → CS0234
            // (field find).
            bool emitsOwnExports =
                !directives.MemberDeclarations.IsDefaultOrEmpty
                || (FileHasAliasedOrDefaultMemberImports(directives)
                    && ExportsEmitter.CollectBridges(directives, filePath, peerExports).Count > 0);
            if (emitsOwnExports)
            {
                string ownExports = $"static {directives.Namespace}.__Exports";
                if (!directives.Usings.Contains(ownExports))
                    directives = directives with { Usings = directives.Usings.Add(ownExports) };
            }

            // ── Stage 4: CSharpEmitter (one partial per component; mixed = concat) ──
            bool multiOrMixed =
                (directives.ComponentDeclarations.IsDefaultOrEmpty ? 0 : directives.ComponentDeclarations.Length) > 1
                || emitsOwnExports;

            if (!multiOrMixed)
            {
                // Single component, no hooks/modules — byte-identical to the pre-mixed-decl path.
                string generatedSource = CSharpEmitter.Emit(filePath, directives, rootNodes, resolver, diagnostics, hookFamilyKeyMap);
                ct.ThrowIfCancellationRequested();
                return new UitkxPipelineResult(hintName, generatedSource, diagnostics.ToImmutableArray());
            }

            // Mixed-decl / multi-component: emit each section as its OWN standalone
            // compilation unit (its own using preamble + namespace block) via a
            // separate AddSource, NOT concatenated into one file. Each unit merges
            // with the others as a `partial` across compilation units — identical to
            // how sibling .uitkx files already compose. Concatenating self-contained
            // units would place later `using` directives after a namespace → CS1529.
            string ExtraHint(string section) =>
                hintName.Substring(0, hintName.Length - ".g.cs".Length) + "." + section + ".g.cs";

            var extraSources = ImmutableArray.CreateBuilder<(string, string)>();
            if (emitsOwnExports)
            {
                string exportsSrc = ExportsEmitter.Emit(
                    filePath, directives, diagnostics, hookFamilyKeyMap, peerExports);
                if (!string.IsNullOrEmpty(exportsSrc))
                    extraSources.Add((ExtraHint("exports"), exportsSrc));
            }

            var componentsToEmit = directives.ComponentDeclarations.IsDefaultOrEmpty
                ? ImmutableArray<ComponentDeclaration>.Empty
                : directives.ComponentDeclarations;
            string? primarySource = null;
            var emittedComponentNames = new HashSet<string>(StringComparer.Ordinal);
            for (int ci = 0; ci < componentsToEmit.Length; ci++)
            {
                ct.ThrowIfCancellationRequested();

                // Two components with the same name in one file would emit duplicate
                // partial classes / members (CS0111/CS0101/CS0579). Flag UITKX0113 and
                // skip the duplicate so the generated code still compiles for the rest.
                if (!emittedComponentNames.Add(componentsToEmit[ci].Name))
                {
                    diagnostics.Add(Diagnostic.Create(
                        UitkxDiagnostics.DuplicateComponentInFile,
                        Location.None,
                        componentsToEmit[ci].Name));
                    continue;
                }

                var cd = SynthesizePerComponent(directives, componentsToEmit[ci]);

                ImmutableArray<AstNode> cRoots;
                if (ci == 0)
                {
                    cRoots = rootNodes; // the first component's markup is already parsed + validated
                }
                else
                {
                    var cThrow = new List<ParseDiagnostic>();
                    var cParsed = UitkxParser.Parse(source, filePath, cd, cThrow);
                    // Later components own their OWN setup-code JSX ranges (the first
                    // component owns rootNodes + setupJsxNodes), so parse + validate them
                    // here too — otherwise a Rules-of-Hooks / structural violation inside a
                    // later component's setup JSX is silently unreported.
                    var cSetupJsx = ParseSetupCodeJsx(source, filePath, cd, cThrow);
                    // Surface the later component's own parse errors (markup + setup JSX).
                    foreach (var pd in cThrow)
                        diagnostics.Add(ParseDiagToRoslyn(pd));
                    cRoots = CanonicalLowering.LowerToRenderRoots(cd, cParsed, filePath);
                    HooksValidator.Validate(cRoots, filePath, diagnostics);
                    if (!cSetupJsx.IsEmpty)
                        HooksValidator.Validate(cSetupJsx, filePath, diagnostics);
                    StructureValidator.Validate(cRoots, filePath, diagnostics, cd);
                    if (!cSetupJsx.IsEmpty)
                        StructureValidator.ValidateNodes(cSetupJsx, filePath, diagnostics);
                }

                string compSrc = CSharpEmitter.Emit(filePath, cd, cRoots, resolver, diagnostics, hookFamilyKeyMap);
                if (ci == 0)
                    primarySource = compSrc; // main component keeps the canonical {file}.g.cs hint
                else
                    // Index-PREFIXED so a component named "inlinehooks"/"inlinemodules" can
                    // never collide with those fixed section labels (→ duplicate AddSource
                    // hint → throw), and two components always get distinct hints via the index.
                    extraSources.Add((ExtraHint("c" + ci + "_" + (cd.ComponentName ?? "")), compSrc));
            }

            ct.ThrowIfCancellationRequested();
            primarySource = SurfaceLocationlessDiagnostics(primarySource, diagnostics, emitDiagStart);
            return new UitkxPipelineResult(
                hintName,
                primarySource,
                diagnostics.ToImmutableArray(),
                extraSources.ToImmutable());
        }

        // ── Helpers ───────────────────────────────────────────────────────────

        // Matches the "name" field in a Unity .asmdef JSON file.
        private static readonly Regex s_asmdefNameRegex = new Regex(
            @"""name""\s*:\s*""([^""]+)""",
            RegexOptions.CultureInvariant
        );

        /// <summary>
        /// Walks up the directory tree from <paramref name="uitkxFilePath"/> looking
        /// for the nearest <c>*.asmdef</c> file. Returns the assembly name declared
        /// in that file's <c>"name"</c> JSON field, or <c>null</c> when no .asmdef
        /// is found (meaning the file belongs to the default <c>Assembly-CSharp</c>
        /// assembly). The walk stops at the <c>Assets</c> directory boundary.
        /// </summary>
        internal static bool IsOwnedByCompilation(string filePath, string? compilationAssemblyName)
        {
            string? ownerAsmName = FindOwningAsmdefAssemblyName(filePath);
            if (ownerAsmName != null)
            {
                return string.Equals(
                    ownerAsmName,
                    compilationAssemblyName,
                    StringComparison.Ordinal
                );
            }

            string asmName = compilationAssemblyName ?? string.Empty;
            bool isEditorAsm = asmName.Contains("Editor", StringComparison.Ordinal);
            bool isEditorFile = IsInsideEditorFolder(filePath);
            return asmName.StartsWith("Assembly-CSharp", StringComparison.Ordinal)
                && isEditorAsm == isEditorFile;
        }

        private static string? FindOwningAsmdefAssemblyName(string uitkxFilePath)
        {
            try
            {
                string? dir = Path.GetDirectoryName(uitkxFilePath);
                while (!string.IsNullOrEmpty(dir))
                {
                    foreach (string asmdef in Directory.GetFiles(dir, "*.asmdef"))
                    {
                        string json = File.ReadAllText(asmdef);
                        var m = s_asmdefNameRegex.Match(json);
                        if (m.Success)
                            return m.Groups[1].Value.Trim();
                    }

                    // Stop at the Assets folder — above it is the Unity project root,
                    // not part of any assembly.
                    string dirName = Path.GetFileName(dir);
                    if (string.Equals(dirName, "Assets", StringComparison.OrdinalIgnoreCase))
                        break;

                    dir = Path.GetDirectoryName(dir);
                }
            }
            catch
            {
                // Never crash the generator on filesystem errors.
            }
            return null;
        }

        /// <summary>
        /// The directory of the <c>.asmdef</c> that OWNS <paramref name="compilation"/> — the
        /// nearest ancestor asmdef (walking up from the compilation's own syntax-tree paths)
        /// whose <c>"name"</c> field equals the compilation's assembly name. <c>null</c> for
        /// asmdef-less assemblies (<c>Assembly-CSharp*</c>) or when no tree path resolves one.
        ///
        /// <para>This exists for the UPM package layout (dev repo consumed via
        /// <c>"file:"</c>/git): the generator's fallback disk scan is <c>{projectRoot}/Assets</c>-rooted,
        /// which finds NOTHING when the assembly's sources physically live outside the host
        /// project (e.g. <c>Ruitk.Samples</c> under the package root). The syntax trees carry the
        /// real physical paths, so their owning-asmdef directory is exactly the root the
        /// assembly's <c>.uitkx</c> files live under — and <see cref="IsOwnedByCompilation"/>
        /// (nearest-asmdef name match) holds for every file found there. For an Assets-resident
        /// asmdef this root is a subset of the Assets scan, so adding it (deduped) changes
        /// nothing for classic layouts.</para>
        ///
        /// <para>Probing is bounded: only the first few distinct tree directories are walked
        /// (generated/in-memory trees have no directory and are skipped). The walk stops at the
        /// <c>Assets</c> boundary (same rule as <see cref="FindOwningAsmdefAssemblyName"/>) and at
        /// the first asmdef seen — a nearest-asmdef whose name differs cannot vouch for this
        /// compilation's root.</para>
        /// </summary>
        internal static string? FindCompilationAsmdefRoot(Compilation compilation)
        {
            string? asmName = compilation.AssemblyName;
            if (string.IsNullOrEmpty(asmName))
                return null;

            const int MaxProbes = 8;
            var probedDirs = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            try
            {
                foreach (var tree in compilation.SyntaxTrees)
                {
                    string path = tree.FilePath;
                    if (string.IsNullOrEmpty(path))
                        continue;
                    if (!Path.IsPathRooted(path))
                    {
                        try { path = Path.GetFullPath(path); }
                        catch { continue; }
                    }

                    string? startDir = Path.GetDirectoryName(path);
                    if (string.IsNullOrEmpty(startDir) || !probedDirs.Add(startDir))
                        continue;

                    string? dir = startDir;
                    while (!string.IsNullOrEmpty(dir))
                    {
                        bool sawAsmdef = false;
                        if (Directory.Exists(dir))
                        {
                            foreach (string asmdef in Directory.GetFiles(dir, "*.asmdef"))
                            {
                                sawAsmdef = true;
                                var m = s_asmdefNameRegex.Match(File.ReadAllText(asmdef));
                                if (m.Success
                                    && string.Equals(m.Groups[1].Value.Trim(), asmName, StringComparison.Ordinal))
                                    return dir;
                            }
                        }
                        if (sawAsmdef)
                            break; // nearest asmdef is a different assembly — try the next tree

                        string dirName = Path.GetFileName(dir);
                        if (string.Equals(dirName, "Assets", StringComparison.OrdinalIgnoreCase))
                            break; // above Assets is the Unity project root, not part of any assembly

                        dir = Path.GetDirectoryName(dir);
                    }

                    if (probedDirs.Count >= MaxProbes)
                        break;
                }
            }
            catch
            {
                // Never crash the generator on filesystem errors.
            }
            return null;
        }


        /// <summary>
        /// The effective C# namespace for a parsed <c>.uitkx</c> file (import/export grammar, leg 3, §4).
        /// The single seam controlling namespace identity — always FILE-keyed since 0.16.0:
        /// explicit <c>@namespace</c> wins; otherwise the path-derived default anchored at the
        /// owning asmdef. A <c>null</c> derivation (no owning asmdef) is the UITKX2310 condition —
        /// the caller reports it; this falls back to the parsed value so the emit never produces
        /// a null namespace.
        /// </summary>
        internal static string? ResolveEffectiveNamespace(DirectiveSet directives, string filePath)
            => EffectiveNamespace.Resolve(
                directives.HasExplicitNamespace, directives.Namespace, filePath,
                fileKeyed: true);

        /// <summary>
        /// The full <c>using</c> list for a component file after hook-container injection (§6.2).
        /// The single seam controlling which hook containers a component sees: only the
        /// container(s) whose source file is named by one of this file's <c>import</c>
        /// declarations (specifier → path via <see cref="ImportResolver"/>, matched against the
        /// peer <see cref="PeerHookContainerInfo.SourceFilePath"/>). C# has no per-method static
        /// import, so the whole matched container is exposed; per-NAME strictness stays a uitkx
        /// diagnostic. Returns <see cref="DirectiveSet.Usings"/> plus the injected
        /// <c>static …</c> entries, order- and dedup-preserving. Pure/host-agnostic and directly
        /// unit-testable.
        /// </summary>
        public static ImmutableArray<string> ResolveInjectedUsings(
            DirectiveSet directives,
            ImmutableArray<PeerHookContainerInfo>? peerHookContainers,
            string filePath,
            ImmutableArray<PeerComponentInfo>? peerComponents = null,
            ImmutableArray<PeerExportsInfo>? peerExports = null)
        {
            var seen = new HashSet<string>(StringComparer.Ordinal);
            var result = ImmutableArray.CreateBuilder<string>();
            foreach (var u in directives.Usings)
                if (seen.Add(u))
                    result.Add(u);

            bool haveHooks = peerHookContainers != null && !peerHookContainers.Value.IsDefaultOrEmpty;

            // Expose only what this file actually imports.
            if (directives.Imports.IsDefaultOrEmpty)
                return result.ToImmutable();

            string importerDir = NormalizeAbs(Path.GetDirectoryName(filePath));
            string? projectRoot = AssetPathUtil.GetProjectRoot(filePath);
            string rootDir = projectRoot != null
                ? NormalizeAbs(projectRoot + "/" + UitkxConfig.LoadRoot(importerDir))
                : importerDir;

            var importedFiles = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            var importedFileNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase); // "file\0name"
            foreach (var imp in directives.Imports)
            {
                string? candidate = ImportResolver.MapSpecifierToPath(
                    importerDir, imp.Specifier, rootDir, out _);
                if (candidate == null)
                    continue;
                string cn = NormalizeAbs(candidate);
                importedFiles.Add(cn);
                foreach (var name in imp.Names)
                    importedFileNames.Add(cn + "\0" + name);
            }

            // ── New-mode targets (ES-modules campaign, U-03) — SG-side mirror of
            //    ImportScopeFacts.ComputeInjectedUsingPayloads' new-mode table ──
            // newModeFiles ALSO gates the legacy loops below: a new-mode target's payloads are
            // decided here alone (alias-aware, per-name); the legacy loops' whole-container /
            // original-name shapes would inject usings the LSP mirror deliberately withholds
            // (editor/build divergence + accidental-capture hazard — audit M4).
            var newModeFiles = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            if (peerExports != null && !peerExports.Value.IsDefaultOrEmpty)
            {
                var exportsByPath = new Dictionary<string, PeerExportsInfo>(StringComparer.OrdinalIgnoreCase);
                foreach (var pe in peerExports.Value)
                {
                    string peKey = NormalizeAbs(pe.SourceFilePath);
                    exportsByPath[peKey] = pe;
                    newModeFiles.Add(peKey);
                }

                foreach (var imp in directives.Imports)
                {
                    string? candidate = ImportResolver.MapSpecifierToPath(
                        importerDir, imp.Specifier, rootDir, out _);
                    if (candidate == null
                        || !exportsByPath.TryGetValue(NormalizeAbs(candidate), out var pe))
                        continue;

                    bool AliasedAt(int k) =>
                        !imp.Aliases.IsDefaultOrEmpty && k < imp.Aliases.Length && imp.Aliases[k] != null;

                    // No exclusive branching — a COMBINED import (`import Def, { a } from` /
                    // `import Def, * as X from`) carries default + named/star parts in one
                    // declaration and every part must yield its payload (LSP mirror identical).
                    if (imp.IsStar && imp.StarAlias != null)
                    {
                        // A component-only target emits NO __Exports unit — an alias to it would
                        // be a file-breaking CS0246 in the importer. Dotted tags resolve through
                        // the tag maps regardless; C#-body refs through a star alias of a
                        // component-only file are per-plan unsupported (U-03 note).
                        bool targetHasExportedMembers = false;
                        if (!pe.Members.IsDefaultOrEmpty)
                            foreach (var m in pe.Members)
                                if (m.IsExported) { targetHasExportedMembers = true; break; }
                        if (targetHasExportedMembers && !ReservedTypeAliases.Contains(imp.StarAlias))
                        {
                            string line = $"{imp.StarAlias} = {pe.Namespace}.__Exports";
                            if (seen.Add(line))
                                result.Add(line);
                        }
                    }

                    if (imp.IsDefault && imp.DefaultAlias != null)
                    {
                        string? defName = pe.DefaultExportName;
                        bool defIsComponent = defName != null && pe.ExportedComponentNames.Contains(defName);
                        if (defIsComponent && !ReservedTypeAliases.Contains(imp.DefaultAlias))
                        {
                            string line = $"{imp.DefaultAlias} = {pe.Namespace}.{defName}";
                            if (seen.Add(line))
                                result.Add(line);
                        }
                        else if (defName != null && !defIsComponent && imp.DefaultAlias == defName)
                        {
                            // Same-name member default ≡ named import: container using — a
                            // bridge would CS0121-collide with the container's public member
                            // (LSP mirror identical). Renamed member defaults still bridge.
                            bool defIsMember = false;
                            if (!pe.Members.IsDefaultOrEmpty)
                                foreach (var m in pe.Members)
                                    if (m.Name == defName) { defIsMember = true; break; }
                            if (defIsMember)
                            {
                                string line = $"static {pe.Namespace}.__Exports";
                                if (seen.Add(line))
                                    result.Add(line);
                            }
                        }
                    }

                    bool exportsContainerAdded = false;
                    for (int k = 0; k < imp.Names.Length; k++)
                    {
                        string name = imp.Names[k];
                        if (pe.ExportedComponentNames.Contains(name))
                        {
                            string bound = AliasedAt(k) ? imp.Aliases[k]! : name;
                            if (!ReservedTypeAliases.Contains(bound))
                            {
                                string line = $"{bound} = {pe.Namespace}.{name}";
                                if (seen.Add(line))
                                    result.Add(line);
                            }
                            continue;
                        }

                        bool isMember = false;
                        if (!pe.Members.IsDefaultOrEmpty)
                            foreach (var m in pe.Members)
                                if (m.IsExported && m.Name == name) { isMember = true; break; }
                        if (isMember && !AliasedAt(k) && !exportsContainerAdded)
                        {
                            string line = $"static {pe.Namespace}.__Exports";
                            if (seen.Add(line))
                                result.Add(line);
                            exportsContainerAdded = true;
                        }
                        // Aliased members bridge (ExportsEmitter) — no using.
                    }
                }
            }

            // Hook: expose the whole owning container (C# has no per-method static import).
            if (haveHooks)
                foreach (var phc in peerHookContainers.Value)
                {
                    if (phc.SourceFilePath == null)
                        continue;
                    if (newModeFiles.Contains(NormalizeAbs(phc.SourceFilePath)))
                        continue; // new-mode block above owns these payloads
                    if (!importedFiles.Contains(NormalizeAbs(phc.SourceFilePath)))
                        continue;
                    string fqn = $"static {phc.Namespace}.{phc.ClassName}";
                    if (seen.Add(fqn))
                        result.Add(fqn);
                }

            // (The legacy module-alias injection lived here until the 0.16.0 removal.)

            // Component (§6.3 extension): alias each imported COMPONENT, same guards the legacy
            // module aliases used (ReservedTypeAliases: the emitter's fixed alias block would
            // CS1537 on a colliding name; same-namespace would CS0576).
            // Tags don't need it (they emit FQN V.Func calls), but C# BODY references to an imported
            // component's type do — `Preset.PresetProps`, `TableView.Column` (nested via the merged
            // module partial) — and those hit CS0246 the moment the peer lives in another namespace
            // (surfaced by path-derived namespaces, where companions in other folders always do).
            // The file import names the exact target, so the alias is the import doing its whole job.
            if (peerComponents != null)
                foreach (var pc in peerComponents.Value)
                {
                    if (pc.SourceFilePath == null || !pc.IsExported)
                        continue;
                    if (newModeFiles.Contains(NormalizeAbs(pc.SourceFilePath)))
                        continue; // new-mode block above owns these payloads (alias-aware)
                    if (!importedFileNames.Contains(NormalizeAbs(pc.SourceFilePath) + "\0" + pc.Name))
                        continue;
                    if (string.Equals(pc.Namespace, directives.Namespace, StringComparison.Ordinal))
                        continue; // same namespace → already accessible; an alias would be CS0576
                    if (ReservedTypeAliases.Contains(pc.Name))
                        continue; // built-in style-type alias wins (see the module comment above)
                    string alias = $"{pc.Name} = {pc.Namespace}.{pc.Name}";
                    if (seen.Add(alias))
                        result.Add(alias);
                }

            return result.ToImmutable();
        }

        /// <summary>
        /// Maps each custom-hook name callable in <paramref name="filePath"/> to its PATH-QUALIFIED
        /// family key <c>{EffectiveNs}.{Container}::{HookName}</c> (§7). Same-file hooks qualify
        /// against this file's own effective namespace + container; imported hooks resolve the import
        /// specifier to the owning peer container (which was built with the SAME
        /// <see cref="ResolveEffectiveNamespace"/> + <c>DeriveContainerClassName</c> the producer uses,
        /// so producer id and consumer key are byte-identical). Consumers (component setup + hook
        /// bodies) qualify their extracted bare names through this map; the runtime matches producer
        /// ids to consumer keys by ordinal string equality, so the two MUST agree exactly.
        /// </summary>
        internal static Dictionary<string, string> BuildHookFamilyKeyMap(
            DirectiveSet directives,
            ImmutableArray<PeerHookContainerInfo>? peerHookContainers,
            string filePath)
        {
            var map = new Dictionary<string, string>(StringComparer.Ordinal);
            string ns = directives.Namespace ?? string.Empty;

            // Same-file plain-declaration hooks (ES-modules campaign, U-06): the container is
            // the per-file __Exports. Imported new-mode hooks need no special case — their peer
            // entries already carry ClassName == "__Exports" (see TryBuildPeerHookContainerInfo).
            if (!directives.MemberDeclarations.IsDefaultOrEmpty)
                foreach (var m in directives.MemberDeclarations)
                    if (m.Kind == DeclKind.Hook && !string.IsNullOrEmpty(m.Name))
                        map[m.Name] = $"{ns}.__Exports::{m.Name}";

            // Imported hooks → resolve each import specifier to its owning peer container.
            if (peerHookContainers != null && !peerHookContainers.Value.IsDefaultOrEmpty
                && !directives.Imports.IsDefaultOrEmpty)
            {
                string importerDir = NormalizeAbs(Path.GetDirectoryName(filePath));
                // Shared with HMR (EffectiveNamespace.UiSourceRootDir) so `~/` hook imports
                // resolve to the same target file on both sides.
                string rootDir = EffectiveNamespace.UiSourceRootDir(filePath) ?? importerDir;

                foreach (var imp in directives.Imports)
                {
                    string? candidate = ImportResolver.MapSpecifierToPath(
                        importerDir, imp.Specifier, rootDir, out _);
                    if (candidate == null)
                        continue;
                    string candN = NormalizeAbs(candidate);
                    foreach (var phc in peerHookContainers.Value)
                    {
                        if (phc.SourceFilePath == null
                            || !string.Equals(NormalizeAbs(phc.SourceFilePath), candN, StringComparison.OrdinalIgnoreCase))
                            continue;
                        // Rename-on-import (G-05): the consumer's body calls the BOUND name, but
                        // the family key must carry the target's ORIGINAL hook name (that is what
                        // the producer registered).
                        for (int k = 0; k < imp.Names.Length; k++)
                        {
                            string name = imp.Names[k];
                            if (!phc.ExportedHookNames.Contains(name))
                                continue;
                            string bound = !imp.Aliases.IsDefaultOrEmpty && k < imp.Aliases.Length
                                ? (imp.Aliases[k] ?? name) : name;
                            map[bound] = $"{phc.Namespace}.{phc.ClassName}::{name}";
                        }
                        break;
                    }
                }
            }
            return map;
        }

        /// <summary>
        /// Type-alias identifiers the component/hook/module emitters emit unconditionally
        /// (<c>using Color = UnityEngine.Color;</c>, <c>using Length = …;</c>, …). An imported
        /// module/component whose name matches one of these cannot be injected as a <c>using</c>
        /// alias (CS1537). Canonical list lives in <see cref="ImportScopeFacts.ReservedTypeAliases"/>
        /// (language-lib) so the LSP virtual doc + HMR share it; this is the SG-side view.
        /// </summary>
        internal static HashSet<string> ReservedTypeAliases => ImportScopeFacts.ReservedTypeAliases;

        private static string NormalizeAbs(string? p) =>
            (p ?? string.Empty).Replace('\\', '/').TrimEnd('/');

        /// <summary>
        /// Builds the two import-alias tag maps for <see cref="PropsResolver"/> (ES-modules
        /// campaign): star alias → target namespace (U-05 dotted tags) and bound component name
        /// (default / rename) → target metadata type name (U-03).
        /// </summary>
        private static (IReadOnlyDictionary<string, string>? StarNs, IReadOnlyDictionary<string, string>? AliasType)
            BuildImportAliasTagMaps(
                DirectiveSet directives, string filePath, ImmutableArray<PeerExportsInfo>? peerExports)
        {
            if (directives.Imports.IsDefaultOrEmpty || peerExports == null || peerExports.Value.IsDefaultOrEmpty)
                return (null, null);

            var exportsByPath = new Dictionary<string, PeerExportsInfo>(StringComparer.OrdinalIgnoreCase);
            foreach (var pe in peerExports.Value)
                exportsByPath[NormalizeAbs(pe.SourceFilePath)] = pe;

            string importerDir = NormalizeAbs(Path.GetDirectoryName(filePath));
            string rootDir = EffectiveNamespace.UiSourceRootDir(filePath) ?? importerDir;

            Dictionary<string, string>? starNs = null;
            Dictionary<string, string>? aliasType = null;
            foreach (var imp in directives.Imports)
            {
                bool interesting = imp.IsStar || imp.IsDefault || !imp.Aliases.IsDefaultOrEmpty;
                if (!interesting)
                    continue;
                string? candidate = ImportResolver.MapSpecifierToPath(
                    importerDir, imp.Specifier, rootDir, out _);
                if (candidate == null || !exportsByPath.TryGetValue(NormalizeAbs(candidate), out var pe))
                    continue;

                // No exclusive branching — combined imports contribute star AND default AND
                // named tag bindings (LSP mirror identical).
                if (imp.IsStar && imp.StarAlias != null)
                {
                    (starNs ??= new Dictionary<string, string>(StringComparer.Ordinal))[imp.StarAlias] = pe.Namespace;
                }
                if (imp.IsDefault && imp.DefaultAlias != null)
                {
                    if (pe.DefaultExportName != null && pe.ExportedComponentNames.Contains(pe.DefaultExportName))
                        (aliasType ??= new Dictionary<string, string>(StringComparer.Ordinal))[imp.DefaultAlias] =
                            $"{pe.Namespace}.{pe.DefaultExportName}";
                }
                for (int k = 0; k < imp.Names.Length && k < imp.Aliases.Length; k++)
                {
                    string? alias = imp.Aliases[k];
                    if (alias == null || !pe.ExportedComponentNames.Contains(imp.Names[k]))
                        continue;
                    (aliasType ??= new Dictionary<string, string>(StringComparer.Ordinal))[alias] =
                        $"{pe.Namespace}.{imp.Names[k]}";
                }
            }
            return (starNs, aliasType);
        }

        /// <summary>
        /// UITKX2113: an import whose target file declares a different <c>@backend</c>
        /// than the importer. Uses the same specifier resolution as
        /// <see cref="BuildImportAliasTagMaps"/>; imports whose target is not in the
        /// peer-exports table (legacy files, unresolved paths) are skipped — legacy
        /// files predate backends and are UI Toolkit by definition, which the null
        /// Backend on their absent entry cannot express, so only NEW-MODE peers are
        /// compared.
        /// </summary>
        private static void AppendCrossBackendImportDiags(
            DirectiveSet directives,
            string filePath,
            ImmutableArray<PeerExportsInfo>? peerExports,
            List<ParseDiagnostic> parseDiags)
        {
            if (directives.Imports.IsDefaultOrEmpty || peerExports == null || peerExports.Value.IsDefaultOrEmpty)
                return;

            var backendByPath = new Dictionary<string, string?>(StringComparer.OrdinalIgnoreCase);
            foreach (var pe in peerExports.Value)
                backendByPath[NormalizeAbs(pe.SourceFilePath)] = pe.Backend;

            string importerDir = NormalizeAbs(Path.GetDirectoryName(filePath));
            string rootDir = EffectiveNamespace.UiSourceRootDir(filePath) ?? importerDir;

            foreach (var imp in directives.Imports)
            {
                string? candidate = ImportResolver.MapSpecifierToPath(
                    importerDir, imp.Specifier, rootDir, out _);
                if (candidate == null || !backendByPath.TryGetValue(NormalizeAbs(candidate), out var peerBackend))
                    continue;
                if (string.Equals(peerBackend, directives.Backend, StringComparison.Ordinal))
                    continue;

                string mine = directives.Backend ?? "uitk";
                string theirs = peerBackend ?? "uitk";
                parseDiags.Add(new ParseDiagnostic
                {
                    Code = "UITKX2113",
                    Severity = ParseSeverity.Error,
                    SourceLine = imp.Line,
                    Message =
                        $"Cross-backend import: '{imp.Specifier}' is a '@backend {theirs}' file but this file targets '{mine}'. "
                        + "A mount renders exactly one backend - move the component to the matching backend, or embed it "
                        + "through an island (UguiHost inside UI Toolkit trees, UitkHost inside uGUI trees).",
                });
            }
        }

        /// <summary>True when any import carries an <c>as</c>-rename or is a default import —
        /// the two forms that lower member imports to typed bridges on the consumer's
        /// <c>__Exports</c> (U-03), forcing an __Exports unit even for a member-less file.</summary>
        private static bool FileHasAliasedOrDefaultMemberImports(DirectiveSet directives)
        {
            if (directives.Imports.IsDefaultOrEmpty)
                return false;
            foreach (var imp in directives.Imports)
            {
                if (imp.IsDefault)
                    return true;
                if (!imp.Aliases.IsDefaultOrEmpty)
                    foreach (var a in imp.Aliases)
                        if (a != null)
                            return true;
            }
            return false;
        }

